// Some Study texts come from e-texts that write characters missing from their fonts as
// private-use code points (U+E000–U+F8FF), which the reader shows as blanks or boxes. Each source
// has its own scheme, so the tables are per book, and every code was checked against a Wikisource
// edition of the same text:
// - 世说新语, 徐霞客游记, 山海经 and 唐宋传奇选 use the 四库全书 e-text codes, mostly variant and
//   taboo-avoidance glyphs (U+EA20 is 玄 without its last stroke). Wikisource's Module:SKchar lists
//   the same glyphs as SKchar n = U+DFFF + n. U+E7E8, U+E7E9 and U+E7EC are the ⿰ ⿱ ⿴ operators
//   of that font; the components after them were lost, so each occurrence has its own rule.
// - 酉阳杂俎, 史记, 牡丹亭 and a few others write a rare character as a private-use radical next
//   to an ordinary character (U+E409 + 霍 is 臛), so sequences run before single characters.
// - 金瓶梅 joins two components with U+E128 (⿰) or U+E127 (⿱): 亦 + U+E127 + 鸟 is 鸾.
// Characters are simplified as OpenCC does, except that a traditional form in the BMP wins over a
// simplified form that only exists outside it (醲, not 𬪩), so ordinary fonts can draw it.
// Codes left alone, such as those inside mis-decoded runs, stay private-use for a later fix.

type PrivateUseTable = {
  // Hex code point -> replacement.
  chars?: Record<string, string>;
  // Literal replacements that run first, for components and context-dependent codes.
  sequences?: Array<[string, string]>;
};


const PRIVATE_USE = /[\uE000-\uF8FF]/g;
// <山几> and {髟曾} spell a character from its components; that fix is done elsewhere.
const PLACEHOLDER = /(<[^<>\n"]{1,12}>|\{[^{}\n"]{1,12}\})/;

export function restorePrivateUseCharacters(text: string, bookId: string): string {
  const table = PRIVATE_USE_TABLES[bookId];
  if (!table || !text.match(PRIVATE_USE)) return text;
  // split() with a capturing group puts the placeholders at odd indexes.
  return text
    .split(PLACEHOLDER)
    .map((piece, i) => (i % 2 === 1 ? piece : restore(piece, table)))
    .join('');
}

function restore(text: string, { chars = {}, sequences = [] }: PrivateUseTable): string {
  let out = text;
  for (const [from, to] of sequences) out = out.split(from).join(to);
  return out.replace(PRIVATE_USE, (c) => chars[c.codePointAt(0)!.toString(16).toUpperCase()] ?? c);
}
